  private storeSession(session: SessionRecord): void {
    this.sessions.set(session.id, session);
    
    // Update indexes
    if (!this.sessionsByStudent.has(session.studentId)) {
      this.sessionsByStudent.set(session.studentId, new Set());
    }
    this.sessionsByStudent.get(session.studentId)!.add(session.id);

    if (!this.sessionsByTeacher.has(session.teacherId)) {
      this.sessionsByTeacher.set(session.teacherId, new Set());
    }
    this.sessionsByTeacher.get(session.teacherId)!.add(session.id);

    if (!this.sessionsByParent.has(session.parentId)) {
      this.sessionsByParent.set(session.parentId, new Set());
    }
    this.sessionsByParent.get(session.parentId)!.add(session.id);
  }

  private querySessions(query: SessionQuery): SessionRecord[] {
    let sessions = Array.from(this.sessions.values());

    if (query.studentId) {
      const studentSessionIds = this.sessionsByStudent.get(query.studentId) || new Set();
      sessions = sessions.filter(s => studentSessionIds.has(s.id));
    }

    if (query.teacherId) {
      const teacherSessionIds = this.sessionsByTeacher.get(query.teacherId) || new Set();
      sessions = sessions.filter(s => teacherSessionIds.has(s.id));
    }

    if (query.status) {
      sessions = sessions.filter(s => query.status!.includes(s.status));
    }

    if (query.dateRange) {
      sessions = sessions.filter(s => 
        s.scheduledStart >= query.dateRange!.start && 
        s.scheduledStart <= query.dateRange!.end
      );
    }

    // Apply sorting
    if (query.sortBy) {
      sessions.sort((a, b) => {
        let aVal: any, bVal: any;
        switch (query.sortBy) {
          case 'date':
            aVal = a.scheduledStart;
            bVal = b.scheduledStart;
            break;
          case 'subject':
            aVal = a.subject;
            bVal = b.subject;
            break;
          case 'status':
            aVal = a.status;
            bVal = b.status;
            break;
          case 'engagement':
            aVal = a.sessionAnalytics.engagementScore;
            bVal = b.sessionAnalytics.engagementScore;
            break;
          default:
            return 0;
        }
        
        const comparison = aVal < bVal ? -1 : aVal > bVal ? 1 : 0;
        return query.sortOrder === 'desc' ? -comparison : comparison;
      });
    }

    // Apply pagination
    if (query.offset || query.limit) {
      const start = query.offset || 0;
      const end = query.limit ? start + query.limit : undefined;
      sessions = sessions.slice(start, end);
    }

    return sessions;
  }

