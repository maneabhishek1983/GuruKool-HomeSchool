  private storeSession(session: SessionRecord): void {
    this.sessions.set(session.id, session);

    // Update indexes
    const studentId = session.studentId;
    const teacherId = session.teacherId;
    const parentId = session.parentId;

    if (studentId) {
      if (!this.sessionsByStudent.has(studentId)) {
        this.sessionsByStudent.set(studentId, new Set());
      }
      this.sessionsByStudent.get(studentId)!.add(session.id);
    }

    if (teacherId) {
      if (!this.sessionsByTeacher.has(teacherId)) {
        this.sessionsByTeacher.set(teacherId, new Set());
      }
      this.sessionsByTeacher.get(teacherId)!.add(session.id);
    }

    if (parentId) {
      if (!this.sessionsByParent.has(parentId)) {
        this.sessionsByParent.set(parentId, new Set());
      }
      this.sessionsByParent.get(parentId)!.add(session.id);
    }
  }

  private querySessions(query: SessionQuery): SessionRecord[] {
    let sessions = Array.from(this.sessions.values());

    if (query.studentId) {
      const studentSessionIds =
        this.sessionsByStudent.get(query.studentId) || new Set();
      sessions = sessions.filter(s => studentSessionIds.has(s.id));
    }

    if (query.teacherId) {
      const teacherSessionIds =
        this.sessionsByTeacher.get(query.teacherId) || new Set();
      sessions = sessions.filter(s => teacherSessionIds.has(s.id));
    }

    if (query.status) {
      sessions = sessions.filter(s => query.status!.includes(s.status));
    }

    if (query.dateRange) {
      sessions = sessions.filter(
        s =>
          s.scheduledStart >= query.dateRange!.start &&
          s.scheduledStart <= query.dateRange!.end
      );
    }

    // Apply sorting
    if (query.sortBy) {
      sessions.sort((a, b) => {
        let aVal: any, bVal: any;
        switch (query.sortBy) {
          case 'date':
            aVal = a.scheduledStart;
            bVal = b.scheduledStart;
            break;
          case 'subject':
            aVal = a.subject;
            bVal = b.subject;
            break;
          case 'status':
            aVal = a.status;
            bVal = b.status;
            break;
          case 'engagement':
            aVal = a.sessionAnalytics.engagementScore;
            bVal = b.sessionAnalytics.engagementScore;
            break;
          default:
            return 0;
        }

        const comparison = aVal < bVal ? -1 : aVal > bVal ? 1 : 0;
        return query.sortOrder === 'desc' ? -comparison : comparison;
      });
    }

    // Apply pagination
    if (query.offset || query.limit) {
      const start = query.offset || 0;
      const end = query.limit ? start + query.limit : undefined;
      sessions = sessions.slice(start, end);
    }

    return sessions;
  }

