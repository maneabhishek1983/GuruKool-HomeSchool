  private hasTimeConflict(session: SessionRecord, start: Date, end: Date): boolean {
    return (
      (start >= session.scheduledStart && start < session.scheduledEnd) ||
      (end > session.scheduledStart && end <= session.scheduledEnd) ||
      (start <= session.scheduledStart && end >= session.scheduledEnd)
    );
  }

