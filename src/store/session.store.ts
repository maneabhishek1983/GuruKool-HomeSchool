  /**
   * Get AI insights for a specific child/student
   */
  public async getAIInsights(childId: string): Promise<AIRecommendation[]> {
    const cachedInsights = this.aiInsightsCache.get(childId);
    if (cachedInsights && this.isCacheValid(childId)) {
      // Convert AIInsight[] to AIRecommendation[] if needed
      return this.convertInsightsToRecommendations(cachedInsights);
    }

    const sessions = await this.getStudentSessions(childId);
    const patterns = await this.detectLearningPatterns(childId);

    const context: AgentContext = {
      user: null,
      sessionData: sessions,
      preferences: {} as any,
      historicalData: {
        sessions,
        analytics: [],
        interactions: [],
      },
      metadata: {
        action: 'get_ai_insights',
        studentId: childId,
        patterns,
      },
    };

    const result = await this.analyticsAgent.execute(context);

    if (result.success && result.data?.insights) {
      this.aiInsightsCache.set(childId, result.data.insights);
      return this.convertInsightsToRecommendations(result.data.insights);
    }

    // Return sample recommendations for now
    return this.getSampleRecommendations(childId);
  }

  /**
   * Convert AI insights to recommendations format
   */
  private convertInsightsToRecommendations(
    insights: AIInsight[]
  ): AIRecommendation[] {
    return insights.map(insight => {
      const recommendation: AIRecommendation = {
        id: insight.id || `insight-${Date.now()}`,
        title: insight.title || 'AI Insight',
        description: insight.description || insight.content,
        severity: insight.severity || 'medium',
        suggestedActions: insight.suggestedActions || [],
        category: insight.category || 'academic',
        confidence: insight.confidence || 0.8,
        generatedAt: insight.generatedAt || new Date(),
      };
      if (insight.studentId !== undefined) {
        recommendation.studentId = insight.studentId;
      }
      if (insight.sessionId !== undefined) {
        recommendation.sessionId = insight.sessionId;
      }
      return recommendation;
    });
  }

