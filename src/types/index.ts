// Core User Types
export interface User {
  id: string;
  email: string;
  name: string;
  role: 'parent' | 'teacher' | 'admin';
  preferences: UserPreferences;
  createdAt: Date;
  lastActive: Date;
}

export interface UserPreferences {
  notifications: NotificationSettings;
  dashboard: DashboardConfig;
  privacy: PrivacySettings;
  accessibility: AccessibilitySettings;
}

export interface NotificationSettings {
  email: boolean;
  push: boolean;
  sms: boolean;
  inApp: boolean;
  frequency: 'immediate' | 'hourly' | 'daily';
}

export interface DashboardConfig {
  layout: 'compact' | 'detailed';
  theme: 'light' | 'dark' | 'auto';
  widgets: string[];
}

export interface PrivacySettings {
  dataSharing: boolean;
  analytics: boolean;
  aiTraining: boolean;
}

export interface AccessibilitySettings {
  fontSize: 'small' | 'medium' | 'large';
  highContrast: boolean;
  reducedMotion: boolean;
  screenReader: boolean;
}

// Session Management Types
export type SessionStatus =
  | 'scheduled'
  | 'in-progress'
  | 'completed'
  | 'cancelled'
  | 'rescheduled';

export interface Session {
  id: string;
  studentId: string;
  teacherId: string;
  parentId: string;
  subject: string;
  scheduledStart: Date;
  scheduledEnd?: Date;
  actualStart?: Date;
  actualEnd?: Date;
  location?: Location;
  status?: SessionStatus;
  notes?: string;
  aiInsights?: AIInsight[];
  attachments?: Attachment[];
  // AI-Enhanced Fields (making them optional for compatibility)
  aiRecommendations?: any[];
  learningPatterns?: any[];
  sessionAnalytics?: any;
  conflictResolution?: any;
  autoGeneratedNotes?: any;
  // Metadata (making them optional for compatibility)
  createdAt?: Date;
  updatedAt?: Date;
  version?: number;
}

export interface Location {
  address: string;
  coordinates: {
    latitude: number;
    longitude: number;
  };
  verified: boolean;
}

export interface Attachment {
  id: string;
  filename: string;
  url: string;
  type: string;
  size: number;
  uploadedAt: Date;
}

// AI and Analytics Types
export interface AIInsight {
  id: string;
  sessionId: string;
  type: 'progress' | 'recommendation' | 'alert' | 'prediction';
  content: string;
  confidence: number;
  metadata: Record<string, any>;
  createdAt: Date;
}

export interface LearningAnalytics {
  studentId: string;
  subject: string;
  progressMetrics: ProgressMetric[];
  learningPatterns: LearningPattern[];
  recommendations: Recommendation[];
  lastUpdated: Date;
}

export interface ProgressMetric {
  metric: string;
  value: number;
  trend: 'improving' | 'stable' | 'declining';
  period: string;
}

export interface LearningPattern {
  pattern: string;
  frequency: number;
  impact: 'positive' | 'neutral' | 'negative';
  confidence: number;
}

export interface Recommendation {
  id: string;
  type: 'action' | 'resource' | 'schedule';
  title: string;
  description: string;
  priority: 'high' | 'medium' | 'low';
  actionable: boolean;
}

