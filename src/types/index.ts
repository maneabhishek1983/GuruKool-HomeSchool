// Academic Standards and Syllabus Types
export type Country = 'UK' | 'US' | 'India';

export interface AcademicStandard {
  country: Country;
  name: string;
  description: string;
  gradeLevels: GradeLevel[];
  subjects: Subject[];
  assessmentMethods: string[];
  learningOutcomes: LearningOutcome[];
}

export interface GradeLevel {
  id: string;
  name: string;
  ageRange: string;
  description: string;
  subjects: Subject[];
  keySkills: string[];
  assessmentCriteria: string[];
}

export interface Subject {
  id: string;
  name: string;
  description: string;
  topics: Topic[];
  skills: string[];
  assessmentMethods: string[];
  resources: string[];
  countrySpecific?: {
    [key in Country]?: {
      name: string;
      topics: Topic[];
      assessmentMethods: string[];
    };
  };
}

export interface Topic {
  id: string;
  name: string;
  description: string;
  learningObjectives: string[];
  activities: string[];
  resources: string[];
  assessmentCriteria: string[];
  difficulty: 'beginner' | 'intermediate' | 'advanced';
}

export interface LearningOutcome {
  id: string;
  category: string;
  outcomes: string[];
  assessmentMethods: string[];
  gradeLevel: string;
}

